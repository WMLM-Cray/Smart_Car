"""gen_goals：从 CSV 或命令行航点生成任务 YAML。

用途：把相对航点 + 原点偏移转成任务文件。实车首测目标集不写死地图坐标——
主线定位完成后，用本脚本按实测原点/朝向生成正式文件（默认 enabled:false，需
显式 --enable 才可用于实车多点模式）。

用法示例：
  # 从 CSV（列 name,x,y,yaw，无表头）生成
  gen_goals --csv waypoints.csv --frame_id map --out mission.yaml

  # 命令行航点 + 原点偏移（车头前方短距离）
  gen_goals --origin 0 0 0 -w 1.0,0.0,0.0 -w 2.0,0.0,0.0 --out mission.yaml

  # 实车首测（默认禁用，须主线单点通过后再 --enable）
  gen_goals -w 1.0,0.0,0.0 -w 2.0,0.0,0.0 --mode multi --out mission_realcar.yaml
"""
import argparse
import math
import sys


def _float3(s):
    parts = s.split(',')
    if len(parts) != 3:
        raise argparse.ArgumentTypeError('expected x,y,yaw, got %r' % s)
    return [float(p) for p in parts]


def build_mission(waypoints, frame_id, mode, loop, on_failure, timeout,
                  xy_tol, yaw_tol, enabled, origin=(0.0, 0.0, 0.0)):
    ox, oy, oyaw = origin
    goals = []
    for i, (name, x, y, yaw) in enumerate(waypoints, start=1):
        goals.append({
            'name': name, 'seq': i,
            'x': x + ox, 'y': y + oy, 'yaw': yaw + oyaw,
        })
    return {
        'mission': {
            'enabled': enabled,
            'frame_id': frame_id,
            'mode': mode,
            'loop': loop,
            'on_failure': on_failure,
            'default': {'timeout': timeout, 'xy_tolerance': xy_tol, 'yaw_tolerance': yaw_tol},
            'goals': goals,
        }
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description='生成任务 YAML')
    ap.add_argument('--csv', help='CSV 文件（列 name,x,y,yaw，无表头）')
    ap.add_argument('-w', '--waypoint', action='append', type=_float3, default=[],
                    help='航点 x,y,yaw（可重复；与 --csv 二选一）')
    ap.add_argument('--origin', type=_float3, default=[0.0, 0.0, 0.0],
                    metavar='X,Y,YAW', help='原点偏移（默认 0,0,0）')
    ap.add_argument('--frame_id', default='map')
    ap.add_argument('--mode', default='multi', choices=['single', 'multi'])
    ap.add_argument('--loop', action='store_true')
    ap.add_argument('--on_failure', default='stop', choices=['stop', 'skip'])
    ap.add_argument('--timeout', type=float, default=30.0)
    ap.add_argument('--xy_tolerance', type=float, default=0.1)
    ap.add_argument('--yaw_tolerance', type=float, default=0.1)
    ap.add_argument('--enable', action='store_true',
                    help='生成 enabled:true（默认 false，实车多点须主线单点通过后再开启）')
    ap.add_argument('--out', required=True, help='输出 YAML 路径')
    args = ap.parse_args(argv)

    waypoints = []
    if args.csv:
        with open(args.csv, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                name, x, y, yaw = line.split(',')
                waypoints.append((name.strip(), float(x), float(y), float(yaw)))
    else:
        if not args.waypoint:
            ap.error('provide --csv or at least one --waypoint')
        for i, (x, y, yaw) in enumerate(args.waypoint, start=1):
            waypoints.append(('p%d' % i, x, y, yaw))

    mission = build_mission(waypoints, args.frame_id, args.mode, args.loop,
                            args.on_failure, args.timeout, args.xy_tolerance,
                            args.yaw_tolerance, args.enable, tuple(args.origin))

    try:
        import yaml
    except ImportError as e:  # pragma: no cover
        print('PyYAML required to write mission YAML: %s' % e, file=sys.stderr)
        return 2

    with open(args.out, 'w', encoding='utf-8') as f:
        f.write('# generated by gen_goals (racecar_mission)\n')
        yaml.safe_dump(mission, f, default_flow_style=False, sort_keys=False)
    print('wrote %s (%d goals, enabled=%s)' % (args.out, len(waypoints), args.enable))
    return 0


if __name__ == '__main__':
    sys.exit(main())
