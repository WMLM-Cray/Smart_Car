#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""赛道A 锥桶 world 生成器(冻结 CSV → trackA.world)。

单源原则:锥桶坐标唯一来源 = docs/track/trackA_cones.csv(trackA_geometry.py
的冻结输出)。本文件不做任何几何决策,只做"CSV → world include"的忠实转换;
黄V禁放带无锥=CSV 里本来就没有(生成器侧已保证,检查器侧对账兜底)。

锥桶资产 = 队友包 racecar_test_assets(提交 7582feb,GPT 验收回执批准接入):
  hwcart_sim/src/racecar_test_assets/models/cone_{blue,red}/
  契约(2026-09-15 审定,检查器逐项断言):
    - 包络=官方规则§3.4:总高 0.63 m / 方底座 0.28×0.28 m
    - 原点=底座底面中心(include pose z=0 即贴地,与 CSV 约定一致)
    - base box 0.28×0.28×0.05(visual==collision)
    - 锥台 mesh meshes/cone_frustum.stl(96 三角,z 0→0.58,底 r0.12/顶 r0.04,
      装在 z=0.05 上;visual==collision 同一 STL)
    - 蓝/红几何字节相同,仅 material diffuse 区分
      (blue 0.05,0.15,0.85 / red 0.85,0.10,0.10)
    - static=true:仅场景/雷达/相机测试,不可验证撞倒推移(GPT 回执确认)
    - 残余 asmp:底座厚 0.05 / 锥台直径(队友 docs/assumptions.md)
  历史角色:本地临时资产 trackA_cone_{blue,red}(40d0e7b→098c3f0,程序生成
  16棱锥+单圆柱碰撞,动态)已随资产接入退役,git 历史可查;其动态低速碰撞
  基线记录见 docs/track/trackA_车辆入trackA验证日志.txt(872c87d)。

队友演示布局(demo_world/sensor_test + config/*.csv)保留在包内但不接入:
本 world 只认冻结 CSV 的 63 锥坐标,不用任何演示布局覆盖 A 赛道。

用法(WSL):
  python3 tools/trackA/trackA_sdf.py [--csv docs/track/trackA_cones.csv]
"""
import argparse
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.normpath(os.path.join(HERE, '..', '..', 'hwcart_sim',
                                    'src', 'racecar_sim'))
# 锥桶资产来源(仅作路径披露;模型本体不拷贝、不修改)
ASSETS = os.path.normpath(os.path.join(
    HERE, '..', '..', 'hwcart_sim', 'src', 'racecar_test_assets',
    'models'))


def gen_world(cones):
    """trackA.world:与 racecar.world 同基础(ground+sun+state 插件)+ 63 include。
    include pose = CSV (x, y) 直接使用(赛道坐标系与 Gazebo world 同 x右/y上,
    原点=赛道外边界左下角;z=0 贴地=队友模型原点在底座底面中心,约定吻合);
    uri 指向队友 cone_{blue,red}(GAZEBO_MODEL_PATH 由 racecar_test_assets
    env-hook 导出,racecar_sim 已声明 exec_depend)。"""
    inc = []
    for c in cones:
        inc.append("    <include>")
        inc.append("      <uri>model://cone_%s</uri>" % c["color"])
        inc.append("      <name>cone_%s</name>" % c["id"])
        inc.append("      <pose>%.6f %.6f 0 0 0 0</pose>" % (c["x"], c["y"]))
        inc.append("    </include>")
    world = """<?xml version="1.0"?>
<!-- TrackA cone field - generated by tools/trackA/trackA_sdf.py from the
     frozen CSV (docs/trackA_cones.csv). Do not edit poses by hand:
     regenerate instead. Cone assets = racecar_test_assets models
     cone_blue / cone_red (official 630/280 envelope, static=true
     test-only); base physics/scene mirrors worlds/racecar.world;
     vehicle is NOT spawned here (added by bringup). -->
<sdf version="1.6">
  <world name="trackA">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>
    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so"/>
{inc}
  </world>
</sdf>
""".format(inc="\n".join(inc))
    path = os.path.join(PKG, 'worlds', 'trackA.world')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(world)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=os.path.normpath(os.path.join(
        HERE, '..', '..', 'docs', 'track', 'trackA_cones.csv')))
    a = ap.parse_args()
    with open(a.csv, encoding='utf-8', newline='') as f:
        cones = [{"id": r["id"].strip(), "color": r["color"].strip(),
                  "x": float(r["x"]), "y": float(r["y"])}
                 for r in csv.DictReader(f)]
    world = gen_world(cones)
    nb = sum(1 for c in cones if c["color"] == "blue")
    nr = len(cones) - nb
    print("cones from CSV: %d total (%d blue + %d red)" % (len(cones), nb, nr))
    print("world -> %s" % world)
    print("cone assets -> %s/cone_{{blue,red}} (racecar_test_assets, "
          "official 630/280 envelope, static)" % ASSETS)


if __name__ == "__main__":
    main()
